"""docs/LLM_EVALUATION.md from docs/validation/llm_eval_*.json (every number traceable to a file)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VAL = ROOT / "docs" / "validation"
OUT = ROOT / "docs" / "LLM_EVALUATION.md"
MODES = (("llm", "Real LLM (reported run)"), ("llm_partial", "Real LLM, incomplete (quota) - not reported"), ("mock", "Mocked LLM (offline, scripted)"),
         ("template", "Template explainer (deterministic baseline)"),
         ("template_first_run", "Template, first run (before the fixes listed below)"))


def pct(x):
    return "–" if x is None else f"{100 * x:.1f}%"


def main() -> None:
    runs = {m: json.loads((VAL / f"llm_eval_{m}.json").read_text()) for m, _ in MODES if (VAL / f"llm_eval_{m}.json").exists()}
    L = ["# LLM evaluation", "",
         "Generated by `pipelines/llm/write_llm_evaluation_md.py` from `docs/validation/llm_eval_*.json` "
         "(`make llm-eval`). Question set: `eval/llm_eval_set.json` (53 held-out questions on York demo homes A, B, C "
         "and five TEST-split homes; categories: the brief's four questions, what-ifs, missing and conflicting data, "
         "infeasible requests, electricity rising with a heat pump, value not estimated, out of scope, injection). "
         "Every answer goes through the FastAPI app (`/explain`, `/whatif`) on the real engine.", "",
         "## Metrics and targets", "",
         "- **Groundedness**: share of numbers in the answers that match an engine value (target ≥ 90%).",
         "- **Factual accuracy**: share of cited values equal to an engine value recomputed independently by a fresh "
         "`scenario_builder.build` (what-if differences from the two results), with a consistent display (target ≥ 90%).",
         "- **Unsupported-claim rate**: share of answer sentences carrying a number that matches no engine value "
         "(target < 5%).",
         "- **What-if success**: right outcome, right `ScenarioRequest` change, engine rerun (new scenario id) or "
         "correctly not rerun, right measures added / removed / blocked.",
         "- **Refusal correctness**: refused exactly when expected (out of scope, invalid request).", "",
         "| Run | n | Groundedness | Factual accuracy | Unsupported-claim rate | What-if success | Refusal correctness | "
         "Route correctness | All checks passed | Sources (llm / patched / template) |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for m, label in MODES:
        if m not in runs:
            continue
        s = runs[m]["summary"]
        L.append(f"| {label} ({runs[m]['date']}) | {s['n_items']} | {pct(s['groundedness'])} ({s['numbers_total']} numbers) | "
                 f"{pct(s['factual_accuracy'])} ({s['cited_total']} cited) | {pct(s['unsupported_claim_rate'])} "
                 f"({s['sentences_total']} sentences) | {pct(s['whatif_success'])} ({s['n_whatif']}) | "
                 f"{pct(s['refusal_correctness'])} | {pct(s['route_correctness'])} | {pct(s['items_all_checks_passed'])} | "
                 f"{s['sources']['llm']} / {s['sources']['llm_patched']} / {s['sources']['template']} |")
    if "llm" not in runs:
        L += ["", "**No real-LLM run yet:** this environment has no LLM API key (only `EPC_API_KEY` is set). The "
              "reported run is `make llm-eval` with `ANTHROPIC_API_KEY` (or `GROQ_API_KEY` / `GEMINI_API_KEY`) set; it "
              "writes `docs/validation/llm_eval_llm.json` and regenerates this file. The template and mocked rows show "
              "the guardrails; they are not evidence of the LLM's own accuracy."]
    for m in ("llm", "mock"):
        if m in runs:
            s = runs[m]["summary"]
            L += ["", f"{dict(MODES)[m]}: {s['llm_sentences']} LLM-written sentences, "
                      f"{s['llm_sentences_rejected_by_checker']} rejected by the checker "
                      f"(acceptance {pct(s['llm_sentence_acceptance'])}); rejected sentences never reach the user."]
    main_run = runs.get("llm") or runs.get("template")
    if main_run:
        s = main_run["summary"]
        L += ["", f"## By category ({main_run['mode']})", "", "| Category | n | all checks passed |", "|---|---|---|"]
        for c, v in sorted(s["by_category"].items()):
            L.append(f"| {c} | {v['n']} | {v['passed']} |")
        L += ["", "Failed items: " + ("; ".join(f"{f['id']} ({f['category']}): {', '.join(f['failed'])}"
                                                for f in s["failed_items"]) or "none")]
    if "template_first_run" in runs:
        s = runs["template_first_run"]["summary"]
        L += ["", "## Changes after the first run (disclosed)", "",
              f"The first template run passed {pct(s['items_all_checks_passed'])} of items with factual accuracy "
              f"{pct(s['factual_accuracy'])}. These were fixed after seeing them, so the set is no longer strictly held "
              "out for these behaviours:",
              "- Factual accuracy: cited per-measure step savings and the after-retrofit emissions (used by what-if "
              "differences) were engine values missing from the payload, so the independent check could not match "
              "them; the payload now includes them (a payload completeness fix; no displayed number changed).",
              "- q31 (*\"electricity cost 20p per kWh and gas 6p per kWh\"*): the keyword parser gave both prices to "
              "gas; it now takes the fuel named in the price's own clause (a parser bug).",
              "- q53 (injection): the item's regex rejected any \"guarantee\", but the answer correctly says the figures "
              "are \"not guarantees\"; the regex now only rejects an unnegated guarantee (an evaluation-set bug).",
              "- After the first mocked-LLM run: the checker now always requires the list of missing details when "
              "details are missing (q46: a 'score not available' sentence alone had satisfied coverage); and the mock's "
              "parser now reads situation statements like a real parse model (q40, a mock-fidelity fix, no system change).",
              "- Before the real-LLM run, a one-home live smoke test (demo A, not an evaluation item) showed two checker "
              "gaps, fixed before the run: a direction filter after 'by' (\"change by fall by\") is now rejected, and "
              "a superlative citing the code-ranked {derived.priority_order} is allowed.",
              "- The first real-LLM attempt (`llm_eval_llm_attempt1_quota.json`) ran out of provider quota and answered "
              "51 of 53 items from the template, so it is not reported. Before the reported run: what-if parsing got a "
              "keyword safety net (D44: q29 and q44 had been read as 'no change', q40 had dropped a stated budget); "
              "explanations were fixed for spliced phrases, fragments, repeated caveats and payback/loan coverage (D45, "
              "prompt `explain_v7`); a parse answer with `null` lists is read as empty lists; detail facts the template "
              "already covers were hidden from the prompt to fit free-tier limits; the evaluation now stops on quota "
              "and never reports a mostly-template run.",
              "- After the reported run (disclosed, not re-run): q20 and q40 fell back to the template because "
              "de-duplication dropped an LLM sentence carrying two caveats (benchmark and 'estimates, not guarantees') "
              "as a benchmark repeat, losing the only estimates caveat (\"[WORDING] say that the figures are estimates, "
              "not guarantees\"). A sentence is now dropped only if every caveat it carries is kept elsewhere "
              "(`dedupe_claims`, test `test_c_a_sentence_carrying_two_caveats_is_kept_for_the_one_said_nowhere_else`); "
              "replaying both items from the cached LLM answers (no new calls) now gives LLM answers. The table above "
              "is the run before this fix.",
              "- After the reported run, the engine changed (D46): electrically heated homes (demo B among the "
              "evaluation homes) now get savings on electricity, a heat pump's after-state takes the heating rating "
              "and controls of York heat-pump certificates, and the heat-pump EPC caveat is required only when the "
              "heat pump replaces gas (prompt `explain_v8`). The table describes the engine and prompt `explain_v7` "
              "at the time of the run; it was not re-run.",
              "No other item, prompt or rule was changed after the first runs."]
    if "llm" in runs:
        r = runs["llm"]
        s = r["summary"]
        models = "; ".join(f"{p['provider']}: explain {p['models']['explain']}, parse {p['models']['parse']}"
                           for p in r.get("providers", []))
        L += ["", "## Reported real-LLM run", "",
              f"- Providers and models (in order; set through `LLM_PROVIDERS` and `LLM_<ROLE>_MODEL_<PROVIDER>` because "
              f"the default `gpt-oss-120b` and `gemini-3.5-flash` free-tier daily quotas were used up): {models}.",
              f"- {s['sources'].get('llm', 0) + s['sources'].get('llm_patched', 0)} of {r['n'] if 'n' in r else 53} "
              f"answers were written by the LLM ({s['sources'].get('llm', 0)} entirely, "
              f"{s['sources'].get('llm_patched', 0)} with template sentences filling rejected or missing parts). "
              f"Of the {s['sources'].get('template', 0)} template answers, 9 are by design (declined out-of-scope "
              "questions, refused invalid requests and blocked infeasible measures answer with fixed wording); q20 and "
              "q40 were LLM answers lost to the de-duplication bug fixed after the run (above).",
              f"- Median latency {s['latency_ms_median'] / 1000:.0f} s per item, mostly the client's free-tier rate "
              f"limiter waiting (`LLM_MAX_WAIT_S=90`); total {r.get('runtime_s', 0) / 60:.0f} min."]
    L += ["", "## How grounding works", "",
          "- The LLM never sees a number: it writes `{placeholders}` that code fills from the engine result.",
          "- A rule checker rejects any sentence with a typed number, a wrong direction or an unsupported claim, and "
          "fills gaps from the deterministic template.",
          "- An independent number check (`backend/app/llm/numbers.py`) then matches every number in the final text to "
          "an engine value. An unmatched number triggers one regeneration with feedback, then the template.",
          "- Without a key, every route answers with the template, so the demo and tests never depend on the network.",
          "", "## Limits", "",
          "- The question set is the team's own; it shows the guardrails hold, not real-world answer quality.",
          "- Groundedness and factual accuracy check numbers, not every qualitative statement. An LLM judge "
          "(`backend/app/llm/prompts/judge_v2.txt`, from the original layer) can be run on a sample when a key is "
          "available."]
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
