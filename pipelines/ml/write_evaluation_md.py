"""M7: docs/EVALUATION.md generated from the JSON reports in docs/validation/ (every number is traceable to a file).

Usage: .venv/bin/python pipelines/ml/write_evaluation_md.py
"""
from __future__ import annotations

import json

from common import ROOT, VALIDATION  # noqa: E402

OUT = ROOT / "docs" / "EVALUATION.md"


def j(name: str) -> dict:
    p = VALIDATION / name
    return json.loads(p.read_text()) if p.exists() else {}


def f(x, k=3, pct=False):
    if x is None:
        return "–"
    if isinstance(x, str):
        return x
    return f"{100 * x:.1f}%" if pct else f"{x:,.{k}f}"


def yes(b) -> str:
    return "pass" if b else "**fail**"


def main() -> None:
    sap, pairs, val, en, rec, test, sl = (j("ml_sap.json"), j("ml_sap_pairs.json"), j("ml_value.json"), j("ml_energy.json"),
                                         j("ml_recommender.json"), j("ml_test.json"), j("ml_slices.json"))
    reg = json.loads((ROOT / "configs" / "model_registry.json").read_text()).get("models", {})
    gate = json.loads((ROOT / "configs" / "value_gate.json").read_text())
    L = ["# Evaluation of the ML models (Phase D)", "",
         "Generated by `pipelines/ml/write_evaluation_md.py` from `docs/validation/ml_*.json` and `configs/*.json`; "
         "do not edit by hand. Validation (val) numbers chose and gated every model; the test split was scored once, "
         "after every choice was frozen (`ml_test.json`). Splits are the existing hashed home splits (NEED: its own split).", "",
         "## What ships", "", "| Model | Version | Shipped | Gates |", "|---|---|---|---|"]
    for name, e in sorted(reg.items()):
        gd = e.get("gate") or {}
        if gd.get("insufficient_labels"):
            g = "not trained: insufficient labels (rules only)"
        else:
            g = ", ".join(f"{k}: {'pass' if v is True else ('fail' if v is False else v)}" for k, v in gd.items()
                          if not isinstance(v, dict))
        L.append(f"| {name} | {e.get('version') or '–'} | {'yes' if e.get('shipped') else 'no'} | {g} |")

    # SAP
    tv, tt = sap.get("val", {}), test.get("sap", {})
    L += ["", "## 1. EPC SAP model (M2) — `ml_sap.json`, `ml_sap_pairs.json`", "",
          "Predicts the SAP score of a recorded home state (train: all certificates of train homes; val/test: latest certificate).", "",
          "| Split | Model | n | MAE | RMSE | R² | ±3 SAP | ±5 SAP | band exact | band ±1 |", "|---|---|---|---|---|---|---|---|---|---|"]
    for split, blk, keys in (("val", tv, (("model", "LightGBM (monotone)"), ("b0_median_type_x_age", "B0 median type×age"), ("b1_ridge", "B1 ridge"))),
                             ("test", tt, (("model", "LightGBM (monotone)"), ("b0", "B0 median type×age"), ("b1", "B1 ridge")))):
        for k, label in keys:
            s = blk.get(k) or {}
            if s:
                L.append(f"| {split} | {label} | {s.get('n', '–')} | {f(s.get('mae'))} | {f(s.get('rmse'))} | {f(s.get('r2'))} | "
                         f"{f(s.get('within_3'), pct=True)} | {f(s.get('within_5'), pct=True)} | {f(s.get('band_exact'), pct=True)} | "
                         f"{f(s.get('band_within_one'), pct=True)} |")
    L += ["", "**Counterfactual pairs** (same home, consecutive certificates, dwelling unchanged, an element changed; "
          "ΔSAP predicted at the new certificate's year):", "", "| Split | n pairs | model MAE | Δ0 baseline MAE | Pearson r | sign agreement |",
          "|---|---|---|---|---|---|"]
    for split, p in (("val", pairs), ("test", tt.get("pairs", {}))):
        if p:
            L.append(f"| {split} | {p['n_pairs']} | {f(p['model']['mae'])} | {f(p['baseline_delta0']['mae'])} | "
                     f"{f(p['model']['pearson_r'])} | {f(p['model']['sign_agreement'], pct=True)} |")
    mono = sap.get("monotonicity", {})
    L += ["", f"Monotonicity: {mono.get('n_homes', '–')} random York homes × each fabric / glazing / controls / PV upgrade: "
          f"{'no' if mono.get('passed') else 'SOME'} negative ΔSAP ({yes(mono.get('passed'))}). Heat pump is unconstrained "
          f"(share of homes with negative ΔSAP: {f((mono.get('heat_pump_unconstrained') or {}).get('share_negative'), pct=True)}).", "",
          "By measure (val pairs, upgrades): " + "; ".join(f"{m} n={v['n']} obs {f(v['obs_mean'], 2)} vs pred {f(v['pred_mean'], 2)}"
                                                        for m, v in (pairs.get("by_measure_upgrade") or {}).items())]

    # value
    vv, vt = val.get("val", {}), test.get("value", {})
    L += ["", "## 2. Property value model (M3) — `ml_value.json`", "",
          "Log price of linked York sales (features from the at-sale certificate). MdAPE = median absolute % error.", "",
          "| Split | Model | n | MdAPE | PPE10 | PPE20 | R² (log) | median bias |", "|---|---|---|---|---|---|---|---|"]
    for split, blk, keys in (("val", vv, (("model", "LightGBM"), ("b0_median_sector_type", "B0 median sector×type"), ("b1_hedonic", "B1 hedonic OLS"))),
                             ("test", vt, (("model", "LightGBM"), ("b0", "B0 median sector×type"), ("b1", "B1 hedonic OLS")))):
        for k, label in keys:
            s = blk.get(k) or {}
            if s:
                L.append(f"| {split} | {label} | {s['n']} | {f(s['mdape'], pct=True)} | {f(s['ppe10'], pct=True)} | {f(s['ppe20'], pct=True)} | "
                         f"{f(s['r2_log'])} | {f(s['median_bias'], pct=True)} |")
    h = val.get("hedonic", {})
    b = h.get("bootstrap", {})
    cc = gate.get("coverage_check")
    L += ["", f"Hedonic β_SAP = {f(h.get('beta_sap'), 5)} log points per SAP point ({f(h.get('pct_per_sap_point'), 3)}% per point); "
          f"sector-clustered bootstrap ({b.get('n_boot')} resamples, {b.get('n_clusters')} sectors) p10 {f(b.get('p10'), 5)}, "
          f"p50 {f(b.get('p50'), 5)}, p90 {f(b.get('p90'), 5)}; share positive {f(b.get('share_positive'), pct=True)}.",
          f"Spatial check (GroupKFold on postcode sector, train): MdAPE {f(val.get('cv', {}).get('spatial_sector_groupkfold_mdape'), pct=True)} "
          f"vs home-grouped {f(val.get('cv', {}).get('home_groupkfold_mdape'), pct=True)}. Time split (train-home sales 2025 → val-home "
          f"sales 2026, n {val.get('time_split', {}).get('n_eval')}): model MdAPE {f(val.get('time_split', {}).get('model', {}).get('mdape'), pct=True)} "
          f"vs B0 {f(val.get('time_split', {}).get('b0', {}).get('mdape'), pct=True)}.",
          f"**Coverage check (D10 condition 3):** 80% split-conformal interval, test coverage "
          f"{f((cc or {}).get('empirical_coverage') if isinstance(cc, dict) else None, pct=True)} → "
          f"{(cc or {}).get('result') if isinstance(cc, dict) else cc}. Value gate status: **{gate.get('status')}**.", "",
          "The uplift is an association between EPC score and price in York sales, not a causal effect of retrofitting."]

    # energy
    L += ["", "## 3. Energy model on NEED (M4) — `ml_energy.json`", "",
          "NEED homes with an EPC band; features York homes share with NEED only. B0 = engine benchmark cells (with region), train only.", "",
          "| Fuel | Split | Subset | n | model MAE kWh | B0 MAE kWh | model MdAPE | B0 MdAPE | P10–P90 coverage (Q) | mean pinball Q / B0 cells |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for fuel, r in (en.get("fuels") or {}).items():
        for sub, key in (("all", "val_overall"), ("Yorkshire", "val_yorkshire")):
            x = r[key]
            L.append(f"| {fuel} | val | {sub} | {x['model']['n']:,} | {f(x['model']['mae_kwh'], 0)} | {f(x['b0']['mae_kwh'], 0)} | "
                     f"{f(x['model']['mdape'], pct=True)} | {f(x['b0']['mdape'], pct=True)} | {f(x['model_quantiles']['coverage_p10_p90'], pct=True)} | "
                     f"{f(x['model_quantiles']['mean_pinball_kwh'], 0)} / {f(x['b0_cell_quantiles']['mean_pinball_kwh'], 0)} |")
        t = (test.get("energy") or {}).get(fuel)
        if t:
            for sub, key in (("all", "overall"), ("Yorkshire", "yorkshire")):
                mm = t["model"][key] if isinstance(t["model"], dict) else None
                q = (t.get("quantiles") or {}).get(key, {})
                L.append(f"| {fuel} | test | {sub} | {t['b0'][key]['n']:,} | {f(mm['mae_kwh'], 0) if mm else 'not shipped'} | "
                         f"{f(t['b0'][key]['mae_kwh'], 0)} | {f(mm['mdape'], pct=True) if mm else '–'} | {f(t['b0'][key]['mdape'], pct=True)} | "
                         f"{f(q.get('coverage_p10_p90'), pct=True)} | {f(q.get('mean_pinball_kwh'), 0)} / "
                         f"{f(t['b0']['cell_quantiles']['mean_pinball_kwh'], 0) if key == 'overall' else '–'} |")
        L.append(f"| {fuel} | gates | | | {', '.join(f'{k}: {yes(v)}' for k, v in r['gates'].items())} | | | | | |")
    sw = en.get("model_switch", {})
    L += ["", f"`configs/model_switch.json`: use_model_baseline = **{sw.get('use_model_baseline')}** ({sw.get('rule', '')}). "
          "NEED homes cannot be linked to York homes, so accuracy on York homes is not measurable with this data."]

    # recommender
    rk = rec.get("ranking_val", {})
    trk = (test.get("recommender") or {}).get("ranking", {})
    L += ["", "## 4. Retrofit relevance ranking (M5) — `ml_recommender.json`", "",
          "Labels: the EPC assessor's recommendations on the latest certificate. Agreement means *consistent with the EPC assessor*, "
          "not feasible or worth doing. Rows: per measure, homes where the engine rule is not infeasible.", "",
          "| Split | Ranking | homes | NDCG@3 | P@1 | MAP |", "|---|---|---|---|---|---|"]
    for split, blk in (("val", rk), ("test", trk)):
        for k in ("model", "b2_engine_order", "b1_prevalence", "b0_rules_random_ties"):
            if k in blk:
                x = blk[k]
                L.append(f"| {split} | {k} | {x['n_homes']:,} | {f(x['ndcg@3'])} | {f(x['precision@1'])} | {f(x['map'])} |")
    L += ["", "| Measure | val positives / rows | model PR-AUC | B1 PR-AUC | model ROC-AUC | test model PR-AUC | test B1 PR-AUC | shipped |",
          "|---|---|---|---|---|---|---|---|"]
    tper = (test.get("recommender") or {}).get("per_measure", {})
    for m, x in (rec.get("per_measure_val") or {}).items():
        t = tper.get(m, {})
        L.append(f"| {m} | {x.get('val_positives')} / {x.get('val_rows')} | {f((x.get('model') or {}).get('pr_auc'))} | "
                 f"{f((x.get('b1') or {}).get('pr_auc'))} | {f((x.get('model') or {}).get('roc_auc'))} | {f((t.get('model') or {}).get('pr_auc'))} | "
                 f"{f((t.get('b1') or {}).get('pr_auc'))} | {'yes' if x.get('shipped') else 'no (' + x.get('status', 'gate') + ')'} |")
    L += ["", "The assessor's software decides recommendations largely from the same certificate fields the model sees, so very "
          "high agreement is expected; it shows the model reproduces assessor practice, not that the measures are right for the home."]

    # slices
    L += ["", "## 5. Slices — `ml_slices.json`", "", "Slices with model error > 1.5× the overall error (n ≥ 30; value n ≥ 20):", ""]
    for split in ("val", "test"):
        s = sl.get(split) or {}
        for k in ("sap_mae", "value_mdape"):
            fl = (s.get(k) or {}).get("flagged", [])
            L.append(f"- {split} {k}: " + (", ".join(f"{x['slice']} (n {x['n']}, {f(x['error'], 3)} vs {f(x['overall'], 3)})" for x in fl) or "none"))
        for fuel, t in ((s.get("energy_mae_kwh") or {}).items()):
            fl = t.get("flagged", [])
            L.append(f"- {split} energy {fuel}: " + (", ".join(f"{x['slice']} (n {x['n']:,})" for x in fl) or "none"))
    L += ["", "## 6. What failed and what ships", "",
          "Models whose gate failed are not loaded by any service (`configs/model_registry.json` shipped = false); the engine keeps its baseline. "
          "See the table at the top; decisions D30–D37 in `docs/DECISIONS.md`."]
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
